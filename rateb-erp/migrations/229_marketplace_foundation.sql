CREATE TABLE IF NOT EXISTS rateb_mp_services (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    public_uuid CHAR(36) NOT NULL,
    company_id INT UNSIGNED NOT NULL,
    provider_id INT UNSIGNED NULL,
    category_id INT UNSIGNED NULL,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(190) NOT NULL,
    name_ar VARCHAR(190) NULL,
    description TEXT NULL,
    base_price DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    currency_code CHAR(3) NOT NULL DEFAULT 'SAR',
    status VARCHAR(40) NOT NULL DEFAULT 'draft',
    created_by INT UNSIGNED NULL,
    updated_by INT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    UNIQUE KEY uq_mp_svc_uuid (public_uuid),
    UNIQUE KEY uq_mp_svc_code (company_id, code),
    INDEX idx_mp_svc_company (company_id, deleted_at),
    INDEX idx_mp_svc_provider (provider_id),
    INDEX idx_mp_svc_category (category_id),
    CONSTRAINT fk_mp_svc_tenant FOREIGN KEY (company_id) REFERENCES rateb_companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_mp_svc_provider FOREIGN KEY (provider_id) REFERENCES rateb_mp_providers(id) ON DELETE SET NULL,
    CONSTRAINT fk_mp_svc_category FOREIGN KEY (category_id) REFERENCES rateb_mp_categories(id) ON DELETE SET NULL
