function hx(string $s): string
{
    return strtoupper(bin2hex($s));
}

function u(string $s): string
{
    if ($s === '') {
        return "''";
    }
    return "CONVERT(UNHEX('" . hx($s) . "') USING utf8mb4)";
}

function esc(string $s): string
{
    return str_replace("'", "''", $s);
}

