<?php
declare(strict_types=1);

/**
 * Phase B — Branch appliance cold-start installer.
 *
 * Creates local SQLite ERP DB, applies full schema, seeds admin tenant,
 * writes serve.env for the local launcher. Does not touch Controllers/Services/Models.
 *
 * Usage:
 *   php -d extension=pdo_sqlite -d extension=sqlite3 bin/hybrid-branch-install.php
 *   php -d extension=pdo_sqlite bin/hybrid-branch-install.php --force
 */

$root = dirname(__DIR__);
define('RATEB_ENV_NO_SESSION', true);
define('RATEB_ROOT', $root);

require_once $root . '/app/Core/Bootstrap.php';
\Rateb\App\Core\Bootstrap::initMinimal($root);

use Rateb\App\Core\BranchSeedService;
use Rateb\App\Core\Database;
use Rateb\App\Core\HybridRuntime;
use Rateb\App\Core\SqliteSchemaBootstrap;

$force = in_array('--force', $argv, true);

echo "=== RATEB Branch Installer (Phase B) ===" . PHP_EOL;

if (!extension_loaded('pdo_sqlite')) {
    fwrite(STDERR, "ERROR: pdo_sqlite required. Run with: php -d extension=pdo_sqlite -d extension=sqlite3 ...\n");
    exit(1);
}

HybridRuntime::ensureBranchStorage();
$sqlitePath = HybridRuntime::sqlitePath();
$serveEnv = HybridRuntime::branchStorageDir() . '/serve.env';
$marker = HybridRuntime::runtimeMarkerPath();

if (is_file($sqlitePath) && !$force) {
    echo "SQLite already exists: {$sqlitePath}" . PHP_EOL;
    echo "Use --force to recreate (DESTROYS local branch data)." . PHP_EOL;
} elseif (is_file($sqlitePath) && $force) {
    Database::disconnect();
    @unlink($sqlitePath);
    @unlink($sqlitePath . '-wal');
    @unlink($sqlitePath . '-shm');
    echo "Removed existing SQLite (--force)." . PHP_EOL;
}

// Trusted branch runtime (installer-written env for local serve only)
$syncKey = bin2hex(random_bytes(32));
$envBody = implode("\n", [
    '# Generated by hybrid-branch-install.php — local appliance only',
    'RATEB_RUNTIME=branch',
    'RATEB_ALLOW_RUNTIME_MARKER=1',
    'RATEB_SQLITE_PATH=' . $sqlitePath,
    'RATEB_DEPLOYMENT=',
    'RATEB_HYBRID_SYNC_ENABLED=1',
    'RATEB_HYBRID_SYNC_SINK=mysql',
    'RATEB_HYBRID_SYNC_KEY=' . $syncKey,
    '',
]);
file_put_contents($serveEnv, $envBody);
file_put_contents($marker, "branch\n");

putenv('RATEB_RUNTIME=branch');
$_ENV['RATEB_RUNTIME'] = 'branch';
putenv('RATEB_ALLOW_RUNTIME_MARKER=1');
$_ENV['RATEB_ALLOW_RUNTIME_MARKER'] = '1';
putenv('RATEB_SQLITE_PATH=' . $sqlitePath);
$_ENV['RATEB_SQLITE_PATH'] = $sqlitePath;
putenv('RATEB_DEPLOYMENT');
unset($_ENV['RATEB_DEPLOYMENT']);
HybridRuntime::reset();
Database::disconnect();

if (!HybridRuntime::shouldUseSqlite()) {
    fwrite(STDERR, "ERROR: HybridRuntime did not select SQLite after installer env.\n");
    exit(1);
}

echo "Opening SQLite: {$sqlitePath}" . PHP_EOL;
$pdo = Database::connection();
$journal = (string) $pdo->query('PRAGMA journal_mode')->fetchColumn();
echo "journal_mode={$journal}" . PHP_EOL;

$schema = SqliteSchemaBootstrap::ensureErpSchema($pdo);
echo 'Schema applied=' . ($schema['applied'] ? 'yes' : 'cached')
    . ' tables≈' . $schema['tables']
    . ' version=' . $schema['version'] . PHP_EOL;

$tableCount = SqliteSchemaBootstrap::countUserTables($pdo);
echo "sqlite_master tables={$tableCount}" . PHP_EOL;
if ($tableCount < 100) {
    fwrite(STDERR, "ERROR: schema incomplete ({$tableCount} tables)\n");
    exit(1);
}

$seed = BranchSeedService::seedMinimalTenant($pdo);
echo "Seeded company_id={$seed['company_id']} user_id={$seed['user_id']} branch_id={$seed['branch_id']}" . PHP_EOL;
echo "Login: {$seed['email']} / {$seed['password']} (or username: admin)" . PHP_EOL;
echo "Wrote: {$serveEnv}" . PHP_EOL;
echo "Marker: {$marker}" . PHP_EOL;
echo PHP_EOL . "Next: php -d extension=pdo_sqlite bin/hybrid-branch-serve.php" . PHP_EOL;
echo "OK" . PHP_EOL;
exit(0);
